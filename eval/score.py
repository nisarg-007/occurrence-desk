"""
Stage 10: score the parser's field extraction against hand-verified gold
records.

eval/gold/<acn>.json holds the CORRECT (path, value) pairs for a handful of
records, independently derived by reading the raw PDF pages - not by
trusting services/worker/parser.py's own output. This is the only kind of
number that means anything here: if the gold labels were generated by the
same code being tested, a bug would happily "agree with itself".

IMPORTANT - read before trusting this number for the final report:
32 records are hand-verified here, not the 50 the work-pack calls for
("budget a full day to make those gold labels") - one per report set for
24 of the 30 sets, plus extra coverage on the structural edge cases found
while building the parser (bare vs. numbered Aircraft/Component/Person,
three aircraft in one record, three separate reporters, a record missing
the Environment section, a record with no Place/Environment at all). They
were transcribed by Claude reading the raw PDF text directly, cross-checked
against - but not copied from - the parser's own output. A full 50-record
gold set, ideally reviewed by a person, is still open work.

Run from the repo root:
    python eval/score.py
"""

import glob
import json
import sys

sys.path.insert(0, "services/worker")
from parser import parse_pdf  # noqa: E402

GOLD_DIR = "eval/gold"


def load_gold():
    records = []
    for path in sorted(glob.glob(f"{GOLD_DIR}/*.json")):
        with open(path) as handle:
            records.append(json.load(handle))
    return records


def find_record(pdf_name: str, acn: str):
    records = parse_pdf(f"services/worker/sample_pdfs/{pdf_name}", document_id=1)
    for r in records:
        if r["acn"] == acn:
            return r
    return None


def as_multiset(fields: list[dict]) -> list[tuple[str, str]]:
    return sorted((f["path"], f["value"]) for f in fields)


def main():
    gold_records = load_gold()
    print(f"Scoring against {len(gold_records)} hand-verified gold records\n")

    total_gold = total_pred = total_correct = 0
    rows = []

    for gold in gold_records:
        predicted = find_record(gold["pdf"], gold["acn"])
        if predicted is None:
            print(f"ACN {gold['acn']}: NOT FOUND by the parser at all - counts as 0/0")
            continue

        gold_pairs = as_multiset(gold["fields"])
        pred_pairs = as_multiset(predicted["fields"])

        # multiset intersection (a duplicate path+value pair must be matched once each)
        gold_remaining = list(gold_pairs)
        correct = 0
        for pair in pred_pairs:
            if pair in gold_remaining:
                gold_remaining.remove(pair)
                correct += 1

        precision = correct / len(pred_pairs) if pred_pairs else 0.0
        recall = correct / len(gold_pairs) if gold_pairs else 0.0
        f1 = 2 * precision * recall / (precision + recall) if (precision + recall) else 0.0

        missing = [p for p in gold_pairs if p not in [pp for pp in pred_pairs]]
        extra = [p for p in pred_pairs if p not in [gp for gp in gold_pairs]]

        rows.append((gold["acn"], gold["pdf"], precision, recall, f1, len(gold_pairs)))
        total_gold += len(gold_pairs)
        total_pred += len(pred_pairs)
        total_correct += correct

        print(
            f"ACN {gold['acn']} ({gold['pdf']}): P={precision:.3f} R={recall:.3f} F1={f1:.3f} "
            f"(gold={len(gold_pairs)} pairs, predicted={len(pred_pairs)} pairs)"
        )
        if missing:
            print(f"  MISSING ({len(missing)}): {missing[:5]}{' ...' if len(missing) > 5 else ''}")
        if extra:
            print(f"  EXTRA   ({len(extra)}): {extra[:5]}{' ...' if len(extra) > 5 else ''}")

    overall_p = total_correct / total_pred if total_pred else 0.0
    overall_r = total_correct / total_gold if total_gold else 0.0
    overall_f1 = (
        2 * overall_p * overall_r / (overall_p + overall_r) if (overall_p + overall_r) else 0.0
    )

    print(
        f"\nextraction  P {overall_p:.3f}  R {overall_r:.3f}  F1 {overall_f1:.3f}  "
        f"(n={len(rows)} records, {total_gold} gold field pairs)"
    )
    print(f"\nNOTE: {len(rows)} hand-verified records, not the full 50 the work-pack specifies.")


if __name__ == "__main__":
    main()
